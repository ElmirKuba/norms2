import type { AdminAccountView } from './admin-account-view.interface';

/**
 * Страница списка людей (2.9.3·10).
 *
 * **Курсор, а не номер страницы.** Список растёт с конца: пока админ листает, кто-то
 * регистрируется, и на смещениях строки начали бы дублироваться и пропадать. Курсор — `id`
 * последнего показанного; в формате `uuidv7___unixmillis` он монотонен по времени, поэтому
 * годится и как ключ сортировки.
 */
export interface AdminAccountPage {
  /** Строки страницы, новые сверху. */
  items: AdminAccountView[];
  /** Курсор для следующей страницы или null, если это конец. */
  nextCursor: string | null;
}
