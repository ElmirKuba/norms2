/** Ответ POST /invites/check — валиден ли код и с какой подписью он выдан. */
export interface CheckInviteResponse {
  /** true, если код существует и не истёк. */
  valid: boolean;
  /**
   * Подпись, с которой пригласивший создавал код («мой брат», «коллега», «по заявке через
   * бота»), или null у кодов без неё.
   *
   * **Зачем показывать её приглашённому.** Экран «Тебя пригласили!» иначе безличный: человек
   * видит факт приглашения, но не видит, кем и зачем он тут нужен. Подпись — единственное, что
   * в этот момент говорит с ним конкретно, поэтому она выводится, а не прячется.
   *
   * ⚠️ Поле уходит по **публичной** ручке: подпись видит любой, у кого есть код. Это приемлемо
   * (код и предназначен получателю), но означает, что `reason` — не приватная заметка
   * пригласившего. Бот в ·11 предупреждает об этом отдельно.
   */
  reason: string | null;
}
