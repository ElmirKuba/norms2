/** DI-токен порта состояния разовых починок данных. */
export const DATA_FIX_STATE = Symbol('DATA_FIX_STATE');

/**
 * Порт состояния разовых починок (2.9.3·25).
 *
 * Хранит две вещи: какие починки уже отработали и список аккаунтов, по которым надо пройти.
 * Отметки живут строками `datafix.<key>` в `app_settings` — таблица уже есть, отдельной заводить
 * не пришлось, а в админский список настроек эти строки не попадают: он показывает реестр, а не
 * всё подряд из таблицы.
 */
export interface DataFixStatePort {
  /**
   * Отработала ли починка.
   * @param key Стабильный ключ починки.
   * @returns `true`, если отметка уже стоит.
   */
  isDone(key: string): Promise<boolean>;

  /**
   * Ставит отметку «отработала».
   * @param key Стабильный ключ починки.
   * @returns Промис завершения.
   */
  markDone(key: string): Promise<void>;

  /**
   * Идентификаторы живых аккаунтов — починки ходят по данным людей.
   * @returns Список PK.
   */
  listAccountIds(): Promise<string[]>;
}
