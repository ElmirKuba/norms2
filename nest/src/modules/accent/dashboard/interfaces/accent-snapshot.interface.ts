/**
 * Компактный срез «Акцента» для **внешних** потребителей — сейчас это «Обзор» личного кабинета
 * (2.9·16). Намеренно уже, чем `DashboardView`: обзор ЛК отвечает на вопрос «как идут мои
 * разделы», а не «что делать сейчас», — за подробностями человек идёт в сам раздел.
 *
 * Живёт в «Акценте», а не в модуле статистики ЛК: срез знает про устройство раздела, и когда в
 * нём что-то поменяется, править надо здесь, а не в чужом домене.
 */

/** Задачи дня в срезе. */
export interface AccentSnapshotToday {
  /** Сколько закрыто (включая «минимум»). */
  done: number;
  /** Сколько всего на сегодня. */
  total: number;
  /** Процент закрытых (0 при пустом дне — не делим на ноль). */
  percent: number;
}

/** Постоянство в срезе — та же пара чисел, что на дашборде раздела. */
export interface AccentSnapshotPersistence {
  /** Итог «дней с действием» — никогда не падает. */
  totalDays: number;
  /** Дней с действием внутри окна. */
  windowDays: number;
  /** Размер окна (дней). */
  windowSize: number;
}

/** Фокусная цель в срезе. */
export interface AccentSnapshotGoal {
  /** Идентификатор — ссылка ведёт прямо в неё. */
  id: string;
  /** Название. */
  title: string;
  /** Прогресс, 0..100. */
  percentage: number;
}

/** Срез раздела «Акцент» для обзора ЛК. */
export interface AccentOverviewSnapshot {
  /** Задачи на сегодня. */
  today: AccentSnapshotToday;
  /** Постоянство. */
  persistence: AccentSnapshotPersistence;
  /** Одна фокусная цель (или самая свежая активная) либо null. */
  focusGoal: AccentSnapshotGoal | null;
  /** Раздел на паузе. */
  isPaused: boolean;
  /**
   * Есть ли у человека хоть что-то своё (привычки/цели/«держусь», кроме примеров). `false` —
   * обзор зовёт начать, а не рисует нули: пустой раздел не должен выглядеть как проваленный.
   */
  hasContent: boolean;
}
