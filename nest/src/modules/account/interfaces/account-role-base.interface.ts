/**
 * AccountRoleBase — связь аккаунта с ролью (2.9.3): содержательные поля без PK и меток.
 *
 * **Многие-ко-многим осознанно** (реш. Elmir 09.08.2026): один человек может быть
 * одновременно и обычным пользователем, и админом — это две строки, а не одно поле
 * `role` в `accounts`. Появится третья роль — появится третья строка, схема не меняется.
 */
export interface AccountRoleBase {
  /** Кому выдана роль. */
  accountId: string;
  /** Какая роль выдана. */
  roleId: string;
}
