/**
 * Постоянство — два числа, отвечающие на **разные вопросы** ([паспорт фичи](../../../../../../docs/sections/accent/gamification-passport.md) §4.1).
 *
 * Порознь они врут: итог у человека, не заходившего месяц, — правда про прошлое, выданная за
 * настоящее; окно без итога прячет весь пройденный путь. Поэтому наружу они идут только парой.
 *
 * **Ни одно из чисел не является ставкой, которую можно проиграть.** Итог не падает никогда,
 * окно восстанавливается само. Классический стрик с обнулением отклонён насовсем (M#B3-5).
 */
export interface PersistenceView {
  /** «Кто я»: сколько всего дней с действием. Монотонно растёт, никогда не падает. */
  totalDays: number;
  /** «Как я сейчас»: сколько дней с действием попало в окно последних `windowSize`. */
  windowDays: number;
  /** Размер окна в днях (константа домена, отдаём явно — фронт не должен её знать наизусть). */
  windowSize: number;
  /** Последний день с действием (`YYYY-MM-DD`) или null, если действий не было ни разу. */
  lastActiveOn: string | null;
  /**
   * Сколько раз человек возвращался после долгого перерыва. **Факт, а не награда:**
   * достижение `returned` выдаётся один раз за всё время, а это число просто показывает правду.
   */
  returnCount: number;
  /**
   * Сколько дней тишины идёт прямо сейчас (0 — сегодня уже было действие). Нужен правилу
   * достижения «Вернулся» и объясняет пустое окно, не обвиняя.
   */
  silenceDays: number;
}
