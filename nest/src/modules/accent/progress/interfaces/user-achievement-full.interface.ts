/**
 * Коды достижений среднего варианта 2.9 — **за поступок, а не за количество**
 * ([паспорт фичи](../../../../../../docs/sections/accent/gamification-passport.md) §4.2).
 *
 * Счётные достижения черновика (`hundred_tasks`, `habit_master`, `milestone_hunter`…) сюда
 * сознательно не входят: они награждают за то, что человек завёл больше сущностей, — это
 * противоречит Принципу 3 «тренажёр вычитания» ([ADR-0049](../../../../../../docs/decisions/0049-accent-product-principles.md)).
 * Они отложены частью 2 вместе с очками.
 */
export const ACHIEVEMENT_CODES = [
  /** Вернулся после 7+ дней тишины. Новый «Феникс» — без понятия сброса серии. */
  'returned',
  /** День с нулём закрытых задач спасён микро-победой. */
  'bad_day_saved',
  /** Лесенка впервые подняла планку — заработано тремя успешными днями подряд. */
  'ladder_raised',
  /** Первая отмеченная задача. */
  'first_step',
  /** Первая микро-победа. */
  'first_micro_win',
  /** Первая закрытая цель. */
  'first_goal',
] as const;

/** Код достижения (производно от `ACHIEVEMENT_CODES`). */
export type AchievementCode = (typeof ACHIEVEMENT_CODES)[number];

/**
 * UserAchievementFull — факт выдачи достижения (колонки 1:1 со схемой `user_achievements`,
 * domain-model §11). **Иммутабелен:** выдали — и всё, отзыва нет.
 *
 * Единственная таблица геймификации 2.9. Всё остальное (постоянство, «возвращался N раз»)
 * считается **проекцией** из трекеров и в БД не хранится — поэтому рассинхрон «журнал против
 * реальности» невозможен. Достижение так не умеет: «вернулся после десяти дней» зависит от
 * момента, когда это случилось, и обязано остаться датой.
 */
export interface UserAchievementFull {
  /** PK — uuidv7___unixmillis (ADR-0016). */
  id: string;
  /** Владелец — FK на `accounts.id` (ON DELETE CASCADE). */
  accountId: string;
  /** Код из каталога. Каталог живёт в коде, не в БД (справочник на шесть строк). */
  code: AchievementCode;
  /** Когда выдано. */
  awardedAt: Date;
  /**
   * Человекочитаемая деталь момента («после 12 дней тишины») — показывается на карточке.
   * Строка, а не jsonb: содержимое всегда идёт прямиком в текст, разбирать его некому,
   * а типизировать jsonb пришлось бы отдельно ради нуля выгоды.
   */
  context: string | null;
}
