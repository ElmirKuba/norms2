/** Что человек просит: попасть внутрь или добавить приглашений. */
/**
 * Что человек просит у бота. `unban` добавлен в 2.9.3·22: снять бан вправе банивший или его
 * предок по ветке, но они могли удалиться или молчать — и тогда у забаненного не оставалось ни
 * одного пути ([ADR-0003, дополнение](../../../../docs/decisions/0003-ban-semantics.md)).
 */
export type TelegramRequestType = 'join' | 'more_invites' | 'unban';

/** Где заявка в жизненном цикле. */
export type TelegramRequestStatus = 'pending' | 'approved' | 'rejected' | 'expired';

/**
 * TelegramRequestPure — содержательные поля заявки (ADR-0033), без id/FK/меток.
 *
 * **Здесь намеренно НЕТ текста заявки** — ни имени, ни возраста, ни «зачем»
 * ([ADR-0064 §10](../../../../docs/decisions/0064-telegram-release-channel.md)). В БД лежит
 * **карточка, а не собранная информация** (формулировка Elmir): кто написал (`chatId`), чего
 * просит, чем закончилось. Сам текст живёт в переписке админа с ботом, а на диск попадает
 * только `ownerMessageId` — ссылка на сообщение, которое бот может переслать по кнопке
 * «Показать текст».
 *
 * Цена решения принята заранее: почистил чат с ботом — решать придётся вслепую. Взамен «мы не
 * храним персональные данные» остаётся правдой без оговорок.
 */
export interface TelegramRequestPure {
  /**
   * Чат заявителя. Пограничный случай по 152-ФЗ: сам по себе не определяет лицо, но для
   * заявки **необходим** — иначе некуда прислать код. Остаётся после закрытия (реш. Elmir)
   * ради защиты от спама, истории отказов и идемпотентности.
   */
  chatId: string;
  /** Тип заявки. */
  type: TelegramRequestType;
  /** Статус. */
  status: TelegramRequestStatus;
  /**
   * Id сообщения с текстом заявки в личке админа — чтобы бот мог переслать его по кнопке.
   * Null, если сообщение не сохранилось или заявка создана иначе.
   */
  ownerMessageId: number | null;
  /**
   * Причина решения — то, что админ написал при одобрении или отказе. У отказа уходит
   * человеку, у одобрения становится подписью к приглашению. Null, если не указана (прочерк).
   */
  decisionReason: string | null;
}
