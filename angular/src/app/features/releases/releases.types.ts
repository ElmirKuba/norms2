/**
 * Строка публичной витрины релизов (`GET /api/v1/releases`).
 *
 * Сознательно не переиспользуем `NotificationView`: у витрины нет `read` и нет `id`.
 * Общий тип пришлось бы делать с необязательными полями, и тогда компилятор перестал бы
 * ловить попытку отметить прочитанным то, что читают анонимно.
 */
export interface ReleaseView {
  /** Ключ ноты (`release-2.9.0`) — он же сегмент URL. */
  key: string;
  /** Заголовок. */
  title: string;
  /** Короткий текст или null. */
  body: string | null;
  /** Путь к `.md` относительно `content/` или null. */
  contentFile: string | null;
  /** Когда нота появилась (ISO-строка с бэка). */
  createdAt: string;
}
