/**
 * CounterplayFull — контрмера, то есть **свой заранее заготовленный ответ** на препятствие
 * (колонки 1:1 со схемой `counterplays`, domain-model §8, ADR-0062). Не совет от продукта:
 * текст пишет человек. Может ссылаться на микро-победу — тогда в момент столкновения сразу
 * запускается её таймер (ADR-0057), от «что делать» до «делаю» один тап.
 *
 * Действенность («помогало N из M») НЕ хранится — вычисляется на чтение из
 * `obstacle_encounters` (ADR-0052); записи без `outcome` в знаменатель не идут.
 */
export interface CounterplayFull {
  /** PK — uuidv7___unixmillis (ADR-0016). */
  id: string;
  /** Родительское препятствие — FK на `obstacles.id` (ON DELETE CASCADE). */
  obstacleId: string;
  /** Что делаю («убрать телефон в другую комнату»). Свободное поле «без ПДн» (ADR-0001). */
  text: string;
  /**
   * Опц. привязка к микро-победе — FK на `micro_wins.id` (ON DELETE SET NULL): контрмера
   * становится запускаемым действием с таймером. null = просто текст.
   */
  linkedMicroWinId: string | null;
  /** Ручной порядок внутри препятствия (ADR-0054). Авто-сортировки по действенности НЕТ. */
  position: number;
  /** Когда создано. */
  createdAt: Date;
  /** Когда изменено. */
  updatedAt: Date;
}
