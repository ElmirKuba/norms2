/** Вид уведомления: релиз / системное / персональное. */
export type NotificationKind = 'release' | 'system' | 'personal';

/**
 * Формат содержимого ноты (2.9.2·4):
 *
 * - `md` — текст в файле `.md`, рендерится мини-рендером и открывается модалкой. Так устроены
 *   все ноты до 2.9.2 и все патчи впредь.
 * - `page` — контент не текст, а **страница фронта** (лендинг релиза): бэк её не хранит и не
 *   отдаёт, он лишь сообщает формат. Страницу подбирает фронт по `key` ноты.
 *
 * **Почему формат живёт в БД, а не выводится из расширения `contentFile`.** У страницы файла
 * нет вовсе, и «вывод по расширению» потребовал бы хранить фиктивный путь вроде `page:2.9.2` —
 * то есть кодировать тип в строке, предназначенной для пути. Явная колонка с `check` говорит
 * правду в схеме и ловит опечатку на уровне БД, а не на экране.
 */
export type NotificationContentFormat = 'md' | 'page';

/**
 * NotificationPure — содержательные поля уведомления (ADR-0033), без id/FK/меток.
 * Контент — ИЛИ короткий `body` (персональные/системные), ИЛИ `contentFile` —
 * путь к `.md` относительно content/ (рич-релизы, раздаётся бэком под /content/),
 * ИЛИ страница фронта (`contentFormat = 'page'`, файла и текста нет вовсе).
 */
export interface NotificationPure {
  /** Вид. */
  kind: NotificationKind;
  /** Заголовок. */
  title: string;
  /** Короткий текст (inline) или null (если рич-контент в файле). */
  body: string | null;
  /** Путь к `.md` относительно content/ или null (если контент в `body` или это страница). */
  contentFile: string | null;
  /** Чем является содержимое: текстом `.md` или страницей фронта. */
  contentFormat: NotificationContentFormat;
}
