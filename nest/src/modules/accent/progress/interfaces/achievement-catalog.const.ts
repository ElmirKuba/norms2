/**
 * Видимость достижения (2.9·17, решение Elmir).
 *
 * - `catalog` — обычное: видно в сетке и до выдачи (с подсказкой «как получить»), и после.
 *   Работает как **цель**: к нему можно идти.
 * - `silent` — **признание момента, а не достижение**. В витрине не показывается ни до, ни
 *   после; человек узнаёт о нём один раз — строкой в колокольчике.
 *
 * **Зачем разделение.** Достижение-цель обязано быть видимым заранее, иначе это лотерея. Но
 * есть события, чьё условие нельзя показывать заранее: увидев «вернись после долгого
 * перерыва», человек получает инструкцию навредить себе — забросить, чтобы вернуться. Такое
 * событие имеет право на тёплое слово в моменте, но не имеет права быть целью.
 */
export type AchievementVisibility = 'catalog' | 'silent';

/** Описание достижения в каталоге. */
export interface AchievementDefinition {
  /** Код (стабилен навсегда — он лежит в БД). */
  code: AchievementCode;
  /** Название. */
  title: string;
  /** Что произошло — текст для карточки уже выданного. */
  description: string;
  /** Как получить — текст для карточки ещё не выданного. Без давления и без «успей». */
  hint: string;
  /** Видимость: обычное достижение или тихое признание. */
  visibility: AchievementVisibility;
}

