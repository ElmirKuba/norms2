/**
 * TodoEventFull — событие, которого ждут дела (справочник со своим CRUD, реш. Elmir 15.08.2026).
 *
 * **Зачем справочник, а не строка в записи.** Одного события ждут сразу несколько дел: «приедет
 * сварщик 27.08» держит и перенос батареи, и переварку труб, и покупку кронштейна. Держи это
 * текстом в каждой записи — и при переносе даты пришлось бы править три места, а разошлись бы
 * они молча.
 *
 * **Почему это не «седьмой список».** Справочник — словарь, а не место для дел: его нечего
 * забрасывать. Тот же класс, что сферы жизни и атрибуты развития.
 *
 * **Состоявшееся событие не удаляется, а отмечается.** Дела, которые его ждали, освобождаются
 * разом — это и есть смысл общего события.
 *
 * **Архива у события нет намеренно.** Поле `archived_at` было заведено вместе с таблицей и
 * убрано в тот же день: механики скрытия ещё нет, а флаг без экрана и без пути назад — ровно то,
 * что запрещено правилом «не заводи состояние, из которого не назовёшь выход». Понадобится —
 * появится вместе с CRUD событий (·D1).
 */
export interface TodoEventFull {
  /** PK — uuidv7___unixmillis (ADR-0016). */
  id: string;
  /** Владелец — FK на `accounts.id`. */
  accountId: string;
  /** Название события («приедет сварщик», «позвонят из МФЦ», «высохнет стяжка»). */
  title: string;
  /**
   * Ожидаемая дата (`YYYY-MM-DD`, опц.). Событие бывает и без даты — «когда позвонят»: у
   * ожидания есть адрес, но нет срока, и это нормальное состояние, а не недозаполненность.
   */
  expectedOn: string | null;
  /** Когда событие состоялось (null — ещё ждём). */
  happenedAt: Date | null;
  /** Создано. */
  createdAt: Date;
  /** Изменено. */
  updatedAt: Date;
}
