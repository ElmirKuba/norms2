/**
 * Состояние привязки Telegram для экрана настроек (2.9.1·14).
 *
 * `chat_id` сюда намеренно не входит: экрану он не нужен, а это идентификатор человека в чужом
 * сервисе.
 */
export interface TelegramLinkStatus {
  /** Привязан ли чат к аккаунту. */
  linked: boolean;
  /** Когда привязали (ISO) или null. */
  linkedAt: string | null;
  /** Разрешил ли человек боту писать ему (отдельное согласие, ·15). */
  notificationsAllowed: boolean;
  /**
   * Имя бота без `@` — экран строит из него ссылку `t.me/…`.
   *
   * Приходит с бэка, а не зашито во фронт: на стейдже и на проде боты **разные**, и захардкоженное
   * имя отправляло бы тестового человека к боевому боту, который выдаёт настоящие приглашения.
   * Пусто — значит бот не настроен, экран честно скажет об этом вместо битой ссылки.
   */
  botUsername: string;
}
