/**
 * AuditEntryBase — запись журнала действий администратора (2.9.3·6): содержательные поля без PK
 * и меток.
 *
 * **Зачем журнал.** С ·3а поверхность доверия расширяется с одного `chat_id` до «любого с ролью
 * `admin`»: админ выдаёт роли, гасит бота, удаляет публикации. Права без следа — доверие на
 * слово; нас трое, и всё равно.
 *
 * **Почему актёр хранится дважды — ссылкой и снимком логина.** Ссылка нужна, чтобы связать записи
 * с живым аккаунтом; снимок — чтобы след пережил удаление этого аккаунта. Каскад тут был бы
 * ошибкой ровно в том случае, ради которого журнал и заводят: удалили аккаунт — и следы его
 * действий исчезли вместе с ним.
 */
export interface AuditEntryBase {
  /** Кто действовал: аккаунт админа или `null`, если действие совершила система (сид, миграция). */
  actorAccountId: string | null;
  /** Снимок логина на момент действия — переживает удаление аккаунта. `null` у системы. */
  actorLogin: string | null;
  /** Машинный код действия: `role.granted`, `setting.changed`, `release.deleted`. */
  action: string;
  /** Над чем действовали: `account`, `setting`, `release`, `telegram_request`. `null` — общее действие. */
  targetType: string | null;
  /** Идентификатор цели: PK аккаунта, ключ настройки или релиза. Не FK — цели разного рода. */
  targetId: string | null;
  /** Человекочитаемый снимок цели (логин, ключ) — чтобы журнал читался без join-ов. */
  targetLabel: string | null;
  /** Подробности действия структурой: что именно поменялось. `null`, если добавить нечего. */
  details: Record<string, unknown> | null;
}
