/**
 * SettingDescription — настройка так, как её видит админка (2.9.3·7): действующее значение плюс
 * ответ на вопрос «откуда оно взялось».
 */
export interface SettingDescription {
  /** Машинный ключ (`telegram.bot.paused`). */
  key: string;
  /** Действующее значение строкой. */
  value: string;
  /** `env` — начальное значение, строки в базе нет; `db` — перекрыто админкой. */
  source: 'env' | 'db';
  /** Кто менял последним (аккаунт админа) или null: система либо значение из `.env`. */
  updatedBy: string | null;
  /** Когда меняли последний раз; null, если значение ни разу не переопределяли. */
  updatedAt: Date | null;
}
