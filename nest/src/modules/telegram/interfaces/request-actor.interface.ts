/**
 * Кто решает заявку (2.9.3·11).
 *
 * **Аккаунт, а не чат.** У решения из админки чата нет вовсе, а квота приглашений и подпись в
 * журнале нужны одинаково обоим входам. Логин хранится снимком рядом с идентификатором по той
 * же причине, что и в журнале: он должен пережить удаление аккаунта.
 */
export interface RequestActor {
  /** Аккаунт решающего — с него списывается квота при выдаче кода. */
  accountId: string;
  /** Логин на момент решения (снимок для журнала). */
  login: string;
}
