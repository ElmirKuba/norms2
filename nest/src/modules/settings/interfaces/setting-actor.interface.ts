/**
 * SettingActor — кто меняет настройку (2.9.3·7).
 *
 * **Объект, а не два параметра подряд**: логин нужен журналу снимком, и пропустить его должно
 * быть трудно. Пока он был необязательным «вторым аргументом», человеческое переключение через
 * админку записывалось в журнал как системное — поймано живой проверкой 10.08.2026.
 *
 * Оба поля `null` означают систему (сид, миграция), а не «неизвестно».
 */
export interface SettingActor {
  /** Аккаунт админа или null, если действует система. */
  accountId: string | null;
  /** Логин админа снимком (переживает удаление аккаунта) или null у системы. */
  login: string | null;
}
