/**
 * AdminAccountView — человек так, как его видит админка (2.9.3·10).
 *
 * ⚠️ **Здесь нет ничего, чего не видно в самом продукте**: логин, псевдоним, роли, источник
 * регистрации, остаток квоты и метки жизненного цикла. Ни хешей, ни ответов на секретные
 * вопросы, ни содержимого чужих разделов — «я же админ» основанием не является.
 */
export interface AdminAccountView {
  /** PK аккаунта. */
  id: string;
  /** Логин. */
  login: string;
  /** Псевдоним. */
  alias: string;
  /** Коды ролей в нижнем регистре. */
  roles: string[];
  /** Как человек попал в продукт. */
  registrationSource: string;
  /** Остаток квоты приглашений. */
  invitesRemaining: number;
  /** Метка деактивации или null. */
  deactivatedAt: Date | null;
  /** Метка soft-delete или null. */
  deletedAt: Date | null;
  /** Когда зарегистрировался. */
  createdAt: Date;
}
