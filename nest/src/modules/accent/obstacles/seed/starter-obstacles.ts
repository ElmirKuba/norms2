import type { ObstacleType } from '../interfaces/obstacle-full.interface';

/** Шаблон стартового препятствия (без `accountId`/`isStarter` — подставляются при севе). */
export interface StarterObstacle {
  /** Название — так, как человек узнаёт помеху в момент, когда она приходит. */
  name: string;
  /** Вид (ось «природа проблемы», ADR-0062). */
  type: ObstacleType;
  /** Когда приходит (повод). */
  trigger: string;
  /** Как узнаю (признаки). */
  symptoms: string;
  /** Заготовленные ответы — 2–3 штуки, короткие и выполнимые прямо сейчас. */
  counterplays: readonly string[];
}

