/**
 * AuditEntryView — строка журнала действий так, как её видит админка (2.9.3·14).
 *
 * **`actorAccountId` наружу не уходит.** Экран отвечает на вопрос «кто, что, когда, над кем», и
 * логина для этого достаточно; PK аккаунта админу не нужен ни для чего, а отдавать
 * идентификаторы «за компанию» — привычка, из-за которой они потом всплывают в URL и логах.
 *
 * **`actorLogin: null` читается как «система», а не «неизвестно».** Сид выдаёт роли при старте, и
 * это тоже изменение прав: запись о нём такая же полноценная, как о человеке.
 */
export interface AuditEntryView {
  /** PK записи. */
  id: string;
  /** Когда действие произошло. */
  createdAt: Date;
  /** Снимок логина действовавшего или `null` — действовала система. */
  actorLogin: string | null;
  /** Машинный код действия: `role.granted`, `setting.changed`, `release.deleted`. */
  action: string;
  /** Над чем действовали: `account`, `setting`, `release`, `telegram_request`. */
  targetType: string | null;
  /** Идентификатор цели. Не FK — цели разного рода. */
  targetId: string | null;
  /** Человекочитаемый снимок цели (логин, ключ). */
  targetLabel: string | null;
  /** Подробности структурой: что именно поменялось. */
  details: Record<string, unknown> | null;
}
