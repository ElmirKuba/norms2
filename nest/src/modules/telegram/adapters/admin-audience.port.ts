/** DI-токен порта «кто здесь админ» (биндится на реализацию в telegram.module). */
export const ADMIN_AUDIENCE = Symbol('ADMIN_AUDIENCE');

/**
 * Порт «кто в боте админ» (2.9.3·3а) — единственный источник правды о правах в Telegram.
 *
 * **Заменил `TELEGRAM_OWNER_CHAT_ID`.** Раньше права жили в двух несвязанных местах: роль — в
 * базе, `chat_id` — в конфиге. Они неизбежно разъезжаются, и второе нельзя ни посмотреть, ни
 * изменить из продукта. Теперь источник один: привязал Telegram человек с ролью `admin` — бот
 * слушается его как админа; привязал обычный пользователь — он обычный пользователь бота.
 *
 * **Права проверяются в момент команды, а не кэшируются.** Сняли роль — человек перестаёт быть
 * админом бота сразу, без перепривязки и перезапуска.
 *
 * **Отвязал Telegram — потерял админку бота.** Это следствие, а не побочный эффект: права
 * привязаны к аккаунту, а не к чату.
 *
 * ⚠️ **Аварийного люка нет намеренно** (реш. Elmir 09.08.2026). Если ни один админ не привязал
 * Telegram — командовать ботом действительно некому, и это нормально: выход дешёвый (зайти в
 * «Нормисы» админом и привязать чат), а люк «действует, когда админских привязок нет» сам по
 * себе тонкая дыра.
 */
export interface AdminAudiencePort {
  /**
   * Админ ли пишет из этого чата.
   * @param chatId Идентификатор чата.
   * @returns Признак админа.
   */
  isAdminChat(chatId: string): Promise<boolean>;

  /**
   * Чаты всех админов, привязавших Telegram, — куда доставлять заявки.
   * @returns Идентификаторы чатов (пусто, если привязок нет).
   */
  adminChatIds(): Promise<string[]>;
}
