/**
 * RoleBase — справочник ролей (2.9.3): содержательные поля без PK и меток.
 *
 * **Справочник, а не enum в коде** (реш. Elmir 09.08.2026). Роль — строка таблицы, на которую
 * ссылается связь `account_roles`. Добавить роль потом = добавить строку, а не выкатывать
 * миграцию с новым значением `check`.
 */
export interface RoleBase {
  /**
   * Машинный код роли (`admin`, `user`) — по нему проверяются права в коде.
   * Уникален без учёта регистра; менять у существующей роли нельзя, иначе разъедутся проверки.
   */
  code: string;
  /** Человеческое название для интерфейса админки. */
  title: string;
  /** Зачем эта роль нужна — чтобы через полгода не гадать, что она открывает. */
  description: string | null;
}
