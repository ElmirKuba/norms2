/**
 * Публичные строки Telegram-области (ответ `GET /telegram/public`).
 *
 * **Только то, что и так публично** — имя бота и ссылка на него. Ничего влияющего на доступ,
 * никаких идентификаторов чатов и секретов: ручка открыта без авторизации, и всё, что сюда
 * попадёт, увидит любой.
 */
export interface TelegramPublicView {
  /** Имя бота без `@` (для текста «напишите @norms2_bot») или пустая строка. */
  botUsername: string;
  /** Ссылка на бота или пустая строка, если бот на этом стенде не настроен. */
  botUrl: string;
  /** Ссылка на канал-витрину или пустая строка. */
  channelUrl: string;
}
