-- Заявки бота переходят на физическое удаление (2.9.3·35, ADR-0068, ADR-0064).
--
-- **Почему миграция вообще нужна, раз режим живёт в коде.** Пока таблица была `paranoid`,
-- удаление проставляло `deleted_at`, и чтения такие строки не видели. Со сменой режима на
-- `paranoid: false` фильтр по `deleted_at` из запросов пропадает — и всё, что было спрятано
-- раньше, **воскресло бы**: закрытая заявка снова попала бы в очередь, а частичный unique
-- `one_pending_per_chat` мог бы упереться в давно похороненную строку. Поэтому спрятанное
-- дочищаем здесь физически: смена политики хранения обязана убрать за собой хвост прошлой.
--
-- Колонку `deleted_at` не трогаем: она есть у всех 33 таблиц по единому правилу
-- (ADR-0068), и её наличие не означает, что таблица `paranoid` — режим задаётся в схеме.
DELETE FROM "telegram_requests" WHERE "deleted_at" IS NOT NULL;
