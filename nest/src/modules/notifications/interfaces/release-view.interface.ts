/**
 * ReleaseView — строка публичной витрины релизов (`GET /releases`, `GET /releases/:key`).
 *
 * Отличия от {@link NotificationView} принципиальные, а не косметические:
 * - **нет `read`** — прочтения (`notification_reads`) остаются приватной механикой ЛК. Витрина
 *   открыта без авторизации, читателя некому приписать, и трогать чужой счётчик непрочитанного
 *   она не должна ([ADR-0064 §5](../../../../docs/decisions/0064-telegram-release-channel.md));
 * - **нет `id`** — публичный идентификатор ноты это `key` (`release-2.9.0`), он же в URL и в
 *   ссылке из поста в канал. Внутренний PK наружу не отдаём: он ничего не даёт читателю и
 *   привязывает публичный адрес к строке БД.
 */
export interface ReleaseView {
  /** Ключ ноты (`release-2.9.0`) — публичный идентификатор и сегмент URL. */
  key: string;
  /** Заголовок. */
  title: string;
  /** Короткий текст или null (у релизных нот обычно null — текст в `.md`). */
  body: string | null;
  /** Путь к `.md` относительно `content/` или null. */
  contentFile: string | null;
  /** Когда строка записана в базу (не дата выпуска). */
  createdAt: Date;
  /** Дата выпуска (2.9.1·15). Null не ожидается у релизов, но поле общее со схемой. */
  publishedAt: Date | null;
}
