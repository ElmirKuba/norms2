import type { NotificationPure } from './notification-pure.interface';

/**
 * NotificationBase — Pure + поля адресации/создания (ADR-0033): `accountId` (null =
 * broadcast всем, set = персональное конкретному), `key` (стабильный ключ для
 * идемпотентного сида релизов; null у персональных/ad-hoc).
 */
export interface NotificationBase extends NotificationPure {
  /** FK на accounts.id — адресат (null = broadcast всем). */
  accountId: string | null;
  /** Уникальный стабильный ключ (идемпотентный сид релизов) или null. */
  key: string | null;
  /**
   * FK на `releases.id` — какую публикацию доставляет это уведомление (ADR-0065);
   * null у персональных и системных, где контент лежит прямо в `body`.
   *
   * `on delete cascade`: удалили релиз — исчезли и доставки, и отметки о прочтении.
   */
  releaseId: string | null;
  /**
   * Когда нота объявлена во внешний канал (Telegram, 2.9.1) или null — ещё не объявляли.
   *
   * **Зачем поле, а не флаг в памяти:** сидер отрабатывает при каждом старте бэка, и без отметки
   * в БД канал получал бы все десять релизов заново на каждый деплой. Публикация идемпотентна
   * именно по этому полю.
   */
  broadcastedAt: Date | null;
  /**
   * Дата **выпуска** релиза (2.9.1·15) или null у персональных уведомлений.
   *
   * **Зачем отдельно от `createdAt`.** `createdAt` — это когда строку записали в базу, а сидер
   * релизов отрабатывает при каждом старте: пересеял одну ноту при отладке — и она уехала
   * наверх в колокольчике у всех, выше свежего релиза. Пять нот, засеянных одной пачкой, и вовсе
   * делят метку с точностью до секунды, и порядок между ними случаен. Дата выпуска — факт о
   * релизе, она должна храниться, а не выводиться из момента записи.
   *
   * Сортировка и показ идут по `COALESCE(published_at, created_at)`: у персональных уведомлений
   * дата создания и есть дата события, отдельное поле им не нужно.
   */
  publishedAt: Date | null;
}
