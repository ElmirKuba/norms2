import type { FeatureFlags } from '../../auth/interfaces/feature-flags.interface';
import type { TelegramPublicView } from '../../telegram/interfaces/telegram-public-view.interface';

/**
 * Всё, что нужно фронту **до входа** (ответ `GET /api/v1/public-config`).
 *
 * Один ответ вместо запроса на область: страница логина и регистрации должна подниматься с
 * одного обращения, а не собирать себя из нескольких.
 *
 * **Свойства не смешиваются.** Флаги отвечают на вопрос «что включено» и меняют поведение,
 * `telegram` — контент (имя бота, ссылка). Лежат рядом, но под своими ключами: иначе через месяц
 * не сказать, что здесь и почему.
 *
 * ⚠️ **Сюда попадает только то, что и так публично.** Ручка открыта без авторизации — всё, что
 * здесь окажется, увидит любой. Ничего влияющего на доступ, никаких идентификаторов и секретов.
 */
export interface PublicConfigView {
  /** Флаги площадки (что включено). */
  features: FeatureFlags;
  /** Публичные строки Telegram-области (куда писать за заявкой). */
  telegram: TelegramPublicView;
}
