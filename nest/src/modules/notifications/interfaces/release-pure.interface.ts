import type { NotificationContentFormat } from './notification-pure.interface';

/**
 * ReleasePure — содержательные поля **публикации** релиза (ADR-0033), без id/меток.
 *
 * **Публикация — не уведомление** ([ADR-0065](../../../../../docs/decisions/0065-release-vs-notification-split.md)).
 * Релиз существует сам по себе и виден снаружи без всякого аккаунта: у него есть публичный адрес
 * (`key`), формат, дата выпуска и факт объявления в канал. Кому и когда его доставили — вопрос
 * другой сущности (`notifications`), и в этой строке его нет вовсе.
 */
export interface ReleasePure {
  /** Публичный идентификатор и сегмент URL (`release-2.9.1`). */
  key: string;
  /** Заголовок. */
  title: string;
  /** Путь к `.md` относительно `content/` или null у ноты-страницы. */
  contentFile: string | null;
  /** Чем является содержимое: текстом `.md` или страницей фронта. */
  contentFormat: NotificationContentFormat;
  /**
   * Дата **выпуска**. Берётся из git (коммит, которым нота появилась в репозитории) и не зависит
   * от того, когда строку записали в базу: сидер отрабатывает при каждом старте, и сортировка по
   * времени записи однажды уже выкинула ноту 1.0.0 наверх колокольчика у всех (2.9.1·15).
   */
  publishedAt: Date | null;
  /**
   * Когда релиз объявлен во внешний канал, или null — ещё не объявляли.
   *
   * Публикация идемпотентна именно по этому полю: без него канал получал бы все релизы заново
   * на каждый деплой.
   */
  broadcastedAt: Date | null;
}
