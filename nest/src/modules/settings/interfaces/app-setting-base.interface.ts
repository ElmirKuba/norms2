/**
 * AppSettingBase — рантайм-настройка (2.9.3·4): содержательные поля без PK и меток.
 *
 * **Зачем таблица, если есть `.env`.** Переменная окружения меняется только перезапуском, а
 * админка должна переключать флаг на живом приложении. `.env` остаётся **начальным значением**:
 * строка появляется в базе, когда её впервые меняют, и с этого момента решает она.
 */
export interface AppSettingBase {
  /** Машинный ключ настройки (`telegram.bot.paused`). Уникален. */
  key: string;
  /** Значение строкой — тип разбирает читатель; так справочник не зависит от типов. */
  value: string;
  /** Кто изменил последним (аккаунт админа) или null, если поставила система. */
  updatedBy: string | null;
}
