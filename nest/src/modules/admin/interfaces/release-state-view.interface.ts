/** Состояние миграций: что в базе против того, что лежит в образе. */
export interface MigrationsState {
  /** Сколько миграций реально применено к базе. */
  applied: number;
  /** Сколько лежит в образе (журнал drizzle-kit). */
  expected: number;
  /** Тег последней применённой или null. */
  last: string | null;
  /**
   * База отстала от кода (`applied < expected`).
   *
   * **Отдельный флаг, а не «сравни два числа глазами»:** это единственная строка на экране, по
   * которой видно «контейнер поднялся на старой базе», и она обязана читаться без арифметики.
   *
   * Флаг только на одну сторону намеренно. Отставшая база опасна: код обращается к колонкам,
   * которых нет. Обратное расхождение (`applied > expected` — база новее образа) работе не
   * мешает, но тоже значит «развёрнуто не то»; оба числа показываются рядом, и такой случай
   * читается с экрана без отдельного флага.
   */
  behind: boolean;
}

/** Счётчики продукта — грубая мера «сколько всего есть». */
export interface ProductCounters {
  /** Живые аккаунты (без удалённых). */
  accounts: number;
  /** Публикации релизов. */
  releases: number;
  /** Доставленные уведомления. */
  notifications: number;
}

/** Последняя публикация и её судьба в канале. */
export interface LastReleaseState {
  /** Публичный ключ (`release-2.9.3`). */
  key: string;
  /** Заголовок. */
  title: string;
  /** Дата выпуска (ISO) или null. */
  publishedAt: Date | null;
  /**
   * Когда объявлена в канал или null.
   *
   * **Ради этого поля вся ручка и написана.** Ошибки доставки в канал глушатся осознанно
   * (ADR-0064), и «посты перестали уходить» видно только по логам. `null` у свежего релиза —
   * ответ на вопрос, который сейчас задаётся глазами по каналу.
   */
  broadcastedAt: Date | null;
}

/**
 * Состояние выпуска (2.9.3·12) — «что сейчас развёрнуто и всё ли доехало».
 */
export interface ReleaseStateView {
  /** Версия продукта из файла `VERSION`. */
  product: string;
  /** Короткий git-SHA билда или пустая строка. */
  commit: string;
  /** Состояние миграций. */
  migrations: MigrationsState;
  /** Счётчики. */
  counters: ProductCounters;
  /** Последняя публикация или null, если публикаций нет вовсе. */
  lastRelease: LastReleaseState | null;
}
