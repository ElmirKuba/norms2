/** DI-токен порта вещания релизов наружу (биндится в notification-core.module). */
export const RELEASE_BROADCAST = Symbol('RELEASE_BROADCAST');

/** Что объявляем: минимум, из которого собирается пост. */
export interface ReleaseAnnouncement {
  /** Стабильный ключ ноты (`release-2.9.1`) — он же основа публичной ссылки. */
  key: string;
  /** Заголовок ноты. */
  title: string;
  /**
   * Путь к `.md` относительно `content/` — источник лида и тезисов поста. **`null` у ноты-
   * страницы** (2.9.2·4): текста, из которого можно собрать тезисы, у неё нет вовсе, и пост
   * тогда состоит из заголовка и ссылки. Текст для таких постов пишется руками (2.9.2·3) —
   * автосборка из лендинга была бы гаданием по вёрстке.
   */
  contentFile: string | null;
}

/**
 * Исходящий порт: «объявить релиз во внешний канал» (2.9.1).
 *
 * Домен знает **что объявить**, но не знает **куда и как**: сегодня это Telegram-канал, вчера был
 * только колокольчик, завтра может добавиться что-то ещё. Та же форма, что у
 * `ACCENT_PROGRESS_NOTIFIER`: удаление фичи = возврат биндинга на логирующую реализацию, и ни
 * одна строка вокруг не меняется.
 *
 * **Best-effort.** Нота уже в БД и уже видна людям в колокольчике; несостоявшийся пост в канале
 * не повод валить старт приложения. Поэтому метод не бросает, а возвращает признак доставки —
 * по нему домен решает, ставить ли отметку `broadcastedAt`.
 */
export interface ReleaseBroadcastPort {
  /**
   * Объявляет релиз.
   * @param announcement Что объявляем.
   * @returns `true`, если доставлено (тогда нота помечается объявленной), иначе `false`.
   */
  announce(announcement: ReleaseAnnouncement): Promise<boolean>;
}
