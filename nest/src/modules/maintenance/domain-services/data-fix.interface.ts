/**
 * Разовая починка данных (2.9.3·25).
 *
 * **Отличие от миграции — принципиальное.** Миграция правит **схему** и пишется на SQL; починка
 * правит **данные** и обязана идти через бизнес-логику: она зовёт `delete()` доменного сервиса и
 * свято верит, что удалила, а как это делает хранилище — не её дело
 * ([ADR-0068](../../../../docs/decisions/0068-deletion-belongs-to-storage.md)). Миграция,
 * трогающая данные по бизнес-правилам, стареет вместе с правилами и однажды начинает врать.
 */
export interface DataFix {
  /** Стабильный ключ: по нему ставится отметка «отработала». Переименование = повторный прогон. */
  readonly key: string;

  /** Что делает — одной строкой, попадёт в лог при прогоне. */
  readonly title: string;

  /**
   * Выполняет починку. Обязана быть **идемпотентной**: повтор на уже починенных данных — no-op.
   * @param accountIds Живые аккаунты.
   * @returns Сколько записей затронуто (для лога).
   */
  run(accountIds: readonly string[]): Promise<number>;
}
