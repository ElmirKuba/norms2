import { domainToUnicode } from 'node:url';

/**
 * Возвращает адрес в человеческом виде: домен из punycode — в юникод.
 *
 * **Зачем.** `PUBLIC_BASE_URL` на стендах записан как `https://stage.xn--h1ahceki4e.xn--p1ai`, и
 * ссылка-приглашение приходила человеку в личку именно такой. Работает она верно, но `xn--`
 * выглядит ровно как фишинг — то есть бьёт по доверию в самый чувствительный момент, при первом
 * контакте с продуктом (поймано на живом прогоне 05.08.2026).
 *
 * Чинить одной лишь правкой `.env` ненадёжно: значение задаётся на каждом стенде отдельно, и
 * достаточно один раз вписать punycode, чтобы всё вернулось. Здесь же адрес приводится к
 * читаемому виду **на выходе**, независимо от того, как он записан в конфиге.
 *
 * Разбирать вручную не пытаемся: `domainToUnicode` из стандартной библиотеки знает правила IDN,
 * включая смешанные домены вида `stage.нормисы.рф`.
 *
 * @param url Абсолютный адрес.
 * @returns Тот же адрес с доменом в юникоде; при неразбираемом вводе — исходная строка.
 */
export function toHumanUrl(url: string): string {
  try {
    const parsed = new URL(url);
    const human = domainToUnicode(parsed.hostname);
    if (human === '' || human === parsed.hostname) {
      return url;
    }
    // Собираем вручную, а не через parsed.href: `URL` нормализует хост обратно в punycode.
    return url.replace(parsed.hostname, human);
  } catch {
    return url;
  }
}
