/**
 * TelegramLinkFull — привязка аккаунта к чату с ботом (`telegram_links`, 2.9.1·14).
 *
 * **Отдельная сущность и отдельное согласие** ([ADR-0064 §12](../../../../docs/decisions/0064-telegram-release-channel.md)).
 * Привязка нужна для заявок на дополнительные приглашения — начислять квоту по словам человека
 * нельзя. Но **сама по себе она не включает уведомления**: человек писал боту, чтобы попасть
 * внутрь, а не чтобы получать сообщения, и молча подменять одно согласие другим мы не будем.
 * Согласие на уведомления спрашивается явно и живёт в своём поле.
 */
export interface TelegramLinkFull {
  /** PK, uuidv7___unixmillis. */
  id: string;
  /** Привязанный аккаунт. */
  accountId: string;
  /** Чат с ботом. */
  chatId: string;
  /**
   * Согласие получать уведомления. `false` — привязка есть, писать нельзя.
   * Отдельное поле, а не факт наличия строки: это два разных согласия.
   */
  notificationsAllowed: boolean;
  /** Когда привязано. */
  createdAt: Date;
  /** Когда изменено. */
  updatedAt: Date;
}
