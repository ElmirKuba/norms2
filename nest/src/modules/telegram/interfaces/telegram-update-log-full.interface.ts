/**
 * TelegramUpdateLogFull — отметка «этот апдейт уже обработан» (`telegram_updates`, 2.9.1·9).
 *
 * **Зачем таблица, а не память процесса.** Telegram повторяет доставку, если вебхук не ответил
 * 200 — в том числе при перезапуске бэка посреди обработки. Отметка в памяти в этот момент
 * теряется, и повтор пройдёт как новый апдейт: заявка создастся дважды, а при нажатии кнопки
 * владельцем — код выдастся дважды.
 *
 * Хранятся только номер и дата: содержимого апдейта здесь нет и быть не должно.
 */
export interface TelegramUpdateLogFull {
  /** `update_id` из Bot API — он же PK. */
  updateId: number;
  /** Когда обработан (по этому полю чистятся старые). */
  createdAt: Date;
}
