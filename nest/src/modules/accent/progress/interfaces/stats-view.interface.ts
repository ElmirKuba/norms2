import type { PersistenceView } from './persistence.interface';

/** Постоянство по одной привычке — та же пара чисел, что и в целом по аккаунту. */
export interface HabitPersistenceItem {
  /** Идентификатор привычки. */
  habitId: string;
  /** Название. */
  title: string;
  /** Постоянство именно этой привычки. */
  persistence: PersistenceView;
}

/** Достижение на экране статистики — выданное или ещё нет. */
export interface AchievementItem {
  /** Код из каталога. */
  code: string;
  /** Название. */
  title: string;
  /** Что произошло (для выданного). */
  description: string;
  /** Как получить (для невыданного). Показываем всегда — путь виден, а не спрятан. */
  hint: string;
  /** Когда выдано (ISO) или null, если ещё нет. */
  awardedAt: string | null;
  /** Деталь момента («после 12 дней тишины») или null. */
  context: string | null;
}

/**
 * Снимок экрана статистики (`GET /accent/stats`, 2.9). Здесь **нет ни одного числа, которое
 * можно набить независимо от жизни**: всё выводится из зафиксированных действий.
 *
 * Достижения отдаются **целиком каталогом**, включая невыданные с подсказкой «как получить»:
 * путь должно быть видно, иначе достижения превращаются в лотерею.
 */
export interface StatsView {
  /** Постоянство по аккаунту: итог + окно. */
  persistence: PersistenceView;
  /** Постоянство по каждой своей привычке (примеры-витрины сюда не попадают). */
  habits: HabitPersistenceItem[];
  /** Весь каталог достижений: выданные — с датой, остальные — с подсказкой. */
  achievements: AchievementItem[];
  /** Сколько достижений уже выдано — чтобы фронт не считал сам. */
  awardedCount: number;
}
