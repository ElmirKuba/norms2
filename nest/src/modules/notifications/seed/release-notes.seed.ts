import type { NotificationContentFormat } from '../interfaces/notification-pure.interface';

/**
 * Описание одной релиз-ноты для сида (F7). `contentFile` — путь и в репозиторном
 * `seed-content/`, и в раздаваемом `content/` (откуда бэк отдаёт `.md`).
 *
 * ⚠️ **Заголовок `##` — это ТЕЗИС, а не рубрика** (правило с 2.9.1·5). Из заголовков второго
 * уровня автоматически собирается маркированный список в посте Telegram-канала, поэтому
 * «Два числа вместо серии» работает, а «Что уже сейчас», «Мелкие улучшения», «Версия» —
 * превращают анонс в оглавление, из которого ничего не понятно. Поймано на исторической ноте
 * `release-2.0.0`: пять заголовков дали пять пустых строк. Пиши заголовок так, чтобы он
 * читался отдельно от текста и что-то утверждал.
 *
 * ⚠️ **В нотах НЕЛЬЗЯ использовать markdown-таблицы.** Рендерер нот (`md-render.util.ts`)
 * умеет только заголовки, списки, `---`, жирный, курсив и ссылки — это мини-рендер без
 * внешних либ, XSS-щит по замыслу. Таблица выведется сырыми `|` и `---`; поймано на
 * ноте 2.9.0 (Elmir, 04.08.2026). Нужна «таблица» — делай список.
 */
export interface ReleaseNoteSeed {
  /** Стабильный идемпотентный ключ (unique в notifications.key). */
  key: string;
  /** Заголовок (в БД и в шапке модалки). */
  title: string;
  /** Путь к `.md` относительно `content/` (и `seed-content/`). У страницы — null. */
  contentFile: string | null;
  /**
   * Формат содержимого (2.9.2·4); опущен — значит `md`.
   *
   * **Правило выбора (реш. Elmir 05.08.2026): патч `*.*.N` — всегда `md`.** Страницу заслуживает
   * то, о чём есть что рассказать снаружи, а «поправили сортировку» рассказывать некому. Иначе
   * каждый мелкий фикс превращался бы в работу дизайнера, и лендинг обесценился бы от частоты.
   * Правило не на память: {@link assertReleaseNoteFormats} проверяет его на старте.
   */
  contentFormat?: NotificationContentFormat;
  /**
   * Дата **выпуска** (2.9.1·15). Взята из git: коммит, которым нота впервые появилась в
   * репозитории. Это факт, а не догадка, и он не зависит от того, когда база засеяна.
   *
   * Время намеренно одинаковое (12:00 UTC) — мы знаем день выпуска, но не час, и
   * притворяться, что знаем, не будем. Совпадения дат разруливаются вторичной сортировкой
   * по номеру версии, а не выдуманными минутами.
   */
  publishedAt: Date;
}

