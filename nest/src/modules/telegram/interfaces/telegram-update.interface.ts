/**
 * Формы апдейта Telegram — **только те поля, которые мы правда читаем**.
 *
 * Полную схему Bot API не описываем сознательно: она огромна, меняется на стороне Telegram и
 * почти вся нам не нужна. Узкий тип здесь работает как фильтр — если однажды понадобится новое
 * поле, его придётся сначала добавить сюда, то есть осознанно.
 *
 * ⚠️ **Тело апдейта не логируется никогда** ([ADR-0064 §10](../../../../docs/decisions/0064-telegram-release-channel.md)):
 * там имя, возраст и «зачем», которые мы обещали не хранить. «Мы не храним» не должно
 * превратиться в «храним, просто в логах».
 */

/** Чат, откуда пришло сообщение. */
export interface TelegramChat {
  /** Идентификатор чата. */
  id: number;
  /** Тип чата (`private` у личек). */
  type?: string;
}

/** Сообщение. */
export interface TelegramMessage {
  /** Идентификатор сообщения в чате. */
  message_id: number;
  /** Чат. */
  chat: TelegramChat;
  /** Текст (у стикеров и фото его нет — это нам и нужно поймать). */
  text?: string;
}

/** Нажатие инлайн-кнопки. */
export interface TelegramCallbackQuery {
  /** Идентификатор нажатия (на него обязателен `answerCallbackQuery`). */
  id: string;
  /** Данные кнопки (у нас — `действие:id-заявки`). */
  data?: string;
  /** Сообщение, под которым кнопка. */
  message?: TelegramMessage;
  /** Кто нажал. */
  from?: { id: number };
}

/** Апдейт целиком. */
export interface TelegramUpdate {
  /** Порядковый номер апдейта — ключ идемпотентности. */
  update_id: number;
  /** Сообщение. */
  message?: TelegramMessage;
  /** Нажатие кнопки. */
  callback_query?: TelegramCallbackQuery;
}
