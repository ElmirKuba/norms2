/**
 * Проверяет, что строка — существующая IANA-зона.
 *
 * **Проверяем через `Intl`, а не по списку-справочнику** (реш. 2.10·A1): список протухает, а зоны
 * меняются политическими решениями — страна отменила переход на летнее время, и справочник,
 * зашитый в код, начинает врать. `Intl` берёт данные из среды выполнения и обновляется вместе с
 * ней.
 * @param value Проверяемая строка.
 * @returns `true`, если зона существует.
 */
export function isValidTimezone(value: string): boolean {
  if (value.trim() === '') {
    return false;
  }
  try {
    // Конструктор бросает RangeError на неизвестной зоне — это и есть проверка.
    new Intl.DateTimeFormat('en-US', { timeZone: value });
    return true;
  } catch {
    return false;
  }
}
