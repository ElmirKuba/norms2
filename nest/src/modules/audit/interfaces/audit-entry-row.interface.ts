import type { AuditEntryFull } from './audit-entry-full.interface';

/**
 * AuditEntryRow — строка журнала **для чтения**: сама запись плюс то, что известно о её цели
 * сегодня (2.9.3·29.2).
 *
 * **Почему отдельный тип, а не поле в `AuditEntryFull`.** `AuditEntryFull` — контракт строки
 * таблицы, колонки сверяются с ним один-в-один; лишнее поле там ломает типизацию схемы (и
 * ломало — поймано сразу). Признак «жив ли аккаунт» вычисляется join-ом, в таблице его нет.
 *
 * **Зачем он нужен.** С 2.9.3·29.1 логин удалённого освобождается: снимок `@petya` в старой
 * записи может означать не того человека, что `@petya` сегодня. Ссылка по `targetId` не путает
 * никогда, но лента читается глазами по логину — поэтому запись говорит прямо, что аккаунта
 * больше нет.
 */
export type AuditEntryRow = AuditEntryFull & {
  /** Жив ли аккаунт-цель. `null` — цель не аккаунт (настройка, релиз, заявка). */
  targetAlive: boolean | null;
  /** Жив ли действовавший. `null` — действовала система, аккаунта не было. */
  actorAlive: boolean | null;
};
