/**
 * Вид записи — что это по природе. Хранится строкой-ключом (varchar), как `DomainKey` и
 * категории микро-побед.
 *
 * **Три вида, а не два списка** (реш. Elmir 15.08.2026):
 * - `idea` — мысль, про которую ещё не решено, делать ли её вообще («а не начать ли бегать»);
 * - `deed` — решено сделать, но не назначено на день («сходить в МФЦ за загранником»);
 * - `purchase` — покупка («глицин»). Отдельный вид, а не подпункт дела: в живом списке Elmir
 *   покупки лежат сами по себе, без привязки к магазину, и живут иначе — их не «делают», их
 *   покупают, и естественно группировать их по месту.
 */
export const TODO_KINDS = ['idea', 'deed', 'purchase'] as const;

/** Вид записи (производен от `TODO_KINDS`). */
export type TodoKind = (typeof TODO_KINDS)[number];

/**
 * Состояние записи.
 *
 * `done` **не убирает запись из списка** — она уходит вниз (правило взято из живого поведения:
 * в заметке Elmir двенадцать закрытых пунктов сохранены осознанно, «что я уже брал» — тоже
 * информация). Спрятать насовсем — это архив, отдельное состояние с путём назад.
 */
export const TODO_STATUSES = ['open', 'done'] as const;

/** Состояние записи (производно от `TODO_STATUSES`). */
export type TodoStatus = (typeof TODO_STATUSES)[number];

/**
 * TodoFull — запись списка дел (колонки 1:1 со схемой, ADR-0033). Per-account сущность.
 *
 * **Зачем эта сущность вообще появилась.** Продукт требовал классифицировать мысль в момент
 * записи: чтобы записать «надо бы начать бегать», человек обязан был решить — цель это,
 * привычка, микро-победа или задача. Даже самый дешёвый путь, разовая задача, требовал **дату и
 * вид обязательными** — и результат измерим: за два с половиной месяца разовых задач заведено
 * **ноль**, а живой список дел Elmir всё это время жил в Apple Notes.
 *
 * Здесь обязателен **только заголовок**. Всё остальное — потом и по желанию.
 *
 * **Подзадача — полноценная запись** (реш. Elmir 15.08.2026): у неё свой статус, своя дата, своё
 * ожидание. Поэтому вложенность рекурсивная (`parentId` на себя), как дерево целей, а не плоский
 * список подпунктов: «оплатить пошлину» и «сдать документы» могут стоять в разных днях.
 */
export interface TodoFull {
  /** PK — uuidv7___unixmillis (ADR-0016). */
  id: string;
  /** Владелец — FK на `accounts.id`. */
  accountId: string;
  /** Родительская запись (подзадача) или null — корневая. Мягкая ссылка на себя же. */
  parentId: string | null;
  /** Вид: идея, дело или покупка. */
  kind: TodoKind;
  /** Заголовок — единственное обязательное поле. */
  title: string;
  /**
   * Свободная заметка (опц.). Сюда ложится то, что в чужих заметочниках идёт отдельными
   * строками: условия («если биметалл, то монтажный комплект»), справки («1 к 4 раствор
   * цемента»), адреса и люди. Не структурируем — структура отпугнула бы от записи.
   */
  note: string | null;
  /** Состояние. */
  status: TodoStatus;
  /** Когда отмечена выполненной (null — открыта). */
  completedAt: Date | null;
  /**
   * Назначенный день (`YYYY-MM-DD`, опц.). Не «дедлайн» и не расписание — просто день, на
   * который человек решил это сделать. Хранится строкой, как `occurred_on` у остальных дневных
   * сущностей: день, однажды приписанный записи, не должен меняться от смены часового пояса.
   */
  plannedOn: string | null;
  /**
   * Ожидание внешнего события (опц., мягкая ссылка на `todo_events.id`).
   *
   * Дело, которое ждёт УК и сварщика, **не является невыполненным** — оно не может быть
   * выполнено раньше срока. Без этого различия счётчик «не сделано» врёт: он показывает долг
   * там, где долга нет.
   */
  waitsForEventId: string | null;
  /** Ожидание даты (`YYYY-MM-DD`, опц.): «не раньше 27.08». */
  waitsUntil: string | null;
  /** Метка-бейдж (опц.): короткая пометка на карточке — место, человек, что угодно. */
  badge: string | null;
  /** В архиве с этого момента (null — не в архиве). Путь назад обязателен (ADR-0068). */
  archivedAt: Date | null;
  /** Порядок в списке (перетаскивание). */
  position: number;
  /** Создана. */
  createdAt: Date;
  /** Изменена. */
  updatedAt: Date;
}
